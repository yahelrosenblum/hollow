// Builds docs/PHYSICS_AUDIT.md from what the audits actually measured. Hand edits would be
// overwritten on purpose: this document may only ever say what a run produced.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const auditDir = join(root, 'docs', 'audit');

const SECTIONS = [
  { file: 'cpu.json', title: 'CPU reference' },
  { file: 'gpu.json', title: 'GPU solver' },
  { file: 'audio.json', title: 'Audio path' },
  { file: 'soak.json', title: 'Long-run soak' },
];

function escapeCell(text) {
  return String(text).replaceAll('|', '\\|');
}

const lines = [
  '# Physics audit',
  '',
  'Generated by `tools/audit-report.mjs` from measured runs. Targets are proposed acceptance criteria; changes to them, with reasons, are in [DECISIONS.md](DECISIONS.md).',
  '',
  'Hollow simulates 2D acoustics. Nothing here is a claim about real 3D rooms.',
  '',
];

let total = 0;
let met = 0;
const misses = [];

for (const { file, title } of SECTIONS) {
  const path = join(auditDir, file);
  lines.push(`## ${title}`, '');
  if (!existsSync(path)) {
    lines.push('Not yet run.', '');
    continue;
  }
  const report = JSON.parse(readFileSync(path, 'utf8'));
  lines.push(`Run: ${report.when}`, '');
  lines.push('| Check | Target | Measured | Result |', '|---|---|---|---|');
  for (const r of report.results) {
    total += 1;
    if (r.pass) met += 1;
    else misses.push(r.label);
    lines.push(`| ${escapeCell(r.label)} | ${escapeCell(r.target)} | ${escapeCell(r.measured)} | ${r.pass ? 'Met' : '**Missed**'} |`);
  }
  lines.push('');
}

lines.splice(6, 0, `**${met} of ${total} checks met their criteria.**`, '');
if (misses.length) {
  lines.splice(8, 0, 'Missed:', '', ...misses.map((m) => `- ${m}`), '');
}

writeFileSync(join(root, 'docs', 'PHYSICS_AUDIT.md'), `${lines.join('\n')}\n`);
process.stdout.write(`${met} of ${total} met\n`);
